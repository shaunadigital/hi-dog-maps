/* Builds js/icons.js: the site's icon set, shared by the map (js/app.js) and
 * the page generator (tools/build-pages.mjs), so the two can never drift.
 *
 * Source: Phosphor Icons (MIT, https://phosphoricons.com), the "regular"
 * (outline) and "fill" (solid) weights, plus three icons Phosphor doesn't
 * have (leash, playground, fence), drawn on the same 256 grid with the same
 * 16-unit stroke so they sit in the set.
 *
 * Usage rule for the site: outline at rest; fill when selected, inside map
 * pins and on any coloured tile (list-card dots, card-strip thumbnails, the
 * detail panel's fallback hero).
 *
 * Usage:
 *   npm pack @phosphor-icons/core && tar xzf phosphor-icons-core-*.tgz
 *   node tools/build-icons.mjs package/assets
 * Then bump ?v= on js/icons.js in index.html and run tools/build-pages.mjs.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS = process.argv[2];
if (!ASSETS) { console.error("usage: node tools/build-icons.mjs <path to @phosphor-icons/core assets>"); process.exit(1); }

// Phosphor names used anywhere on the site.
const PHOSPHOR = [
  // place types
  "paw-print", "tree", "waves", "mountains", "bowl-food",
  // leash, details
  "dog", "shield-check", "clock", "list-checks", "warning",
  // actions
  "navigation-arrow", "arrow-square-out", "map-pin", "map-pin-simple", "crosshair", "magnifying-glass",
  // views and controls
  "map-trifold", "globe-hemisphere-west", "list-bullets", "sliders-horizontal", "arrows-out", "arrows-in",
  // amenities
  "car", "toilet", "shower", "soccer-ball", "umbrella-simple", "picnic-table", "chair", "tent", "drop",
  "lifebuoy", "path", "basketball", "tennis-ball", "barbell",
  // rules guide
  "books", "compass"
];

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
const icons = {};
for (const n of PHOSPHOR) {
  icons[n] = {
    r: inner(readFileSync(join(ASSETS, "regular", `${n}.svg`), "utf8")),
    f: inner(readFileSync(join(ASSETS, "fill", `${n}-fill.svg`), "utf8"))
  };
}

// Drawn to match: 256 grid, 16-unit round strokes (outline), solid shapes (fill).
const S = 'fill="none" stroke="currentColor" stroke-width="16" stroke-linecap="round" stroke-linejoin="round"';
icons["leash"] = {
  // collar ring, leash, handle loop
  r: `<g ${S}><circle cx="76" cy="76" r="36"/><path d="M101.5 101.5C146 146 166 174 171 194"/><circle cx="180" cy="204" r="28"/></g>`,
  f: `<circle cx="76" cy="76" r="44"/><circle cx="180" cy="204" r="36"/><path d="M101.5 101.5C146 146 166 174 171 194" fill="none" stroke="currentColor" stroke-width="22" stroke-linecap="round"/>`
};
icons["fence"] = {
  // three pointed pickets on two rails
  r: `<g ${S}><path d="M48 216V88l24-32 24 32v128M160 216V88l24-32 24 32v128"/><path d="M104 216V72l24-32 24 32v144"/><path d="M24 120h208M24 176h208"/></g>`,
  f: `<path d="M44 220V86l28-36 28 36v134ZM100 220V70l28-36 28 36v150ZM156 220V86l28-36 28 36v134Z"/><path d="M20 120h216M20 176h216" fill="none" stroke="currentColor" stroke-width="20" stroke-linecap="round"/>`
};
icons["playground"] = {
  // ladder and slide
  r: `<g ${S}><path d="M48 224V48M96 224V48M48 96h48M48 144h48M48 192h48"/><path d="M96 48c64 0 72 112 136 176"/><path d="M24 224h216"/></g>`,
  f: `<g fill="none" stroke="currentColor" stroke-width="24" stroke-linecap="round" stroke-linejoin="round"><path d="M48 224V48M96 224V48M48 96h48M48 144h48M48 192h48"/><path d="M96 48c64 0 72 112 136 176"/><path d="M24 224h216"/></g>`
};

const out = `/* Generated by tools/build-icons.mjs. Do not edit by hand.
 * Icons: Phosphor Icons (MIT, https://phosphoricons.com), regular and fill
 * weights, plus leash, fence and playground drawn to match.
 * Rule: outline at rest; fill when selected, in map pins and on coloured tiles. */
var HDM_ICONS = ${JSON.stringify(icons)};

/* What each place type, and each amenity keyword, is drawn with. */
var HDM_ICON_FOR = {
  "dog-park": "paw-print", "park": "tree", "beach": "waves", "trail": "mountains", "patio": "bowl-food",
  "off-leash": "dog", "leashed": "leash"
};
var HDM_AMENITY_ICONS = [
  [/parking/i, "car"], [/restroom|toilet/i, "toilet"], [/shower/i, "shower"],
  [/fenced|fence|small & large dog/i, "fence"], [/playground/i, "playground"],
  [/picnic|bbq|grill/i, "picnic-table"], [/shade/i, "umbrella-simple"],
  [/water (bowl|station|fountain)|drinking water|water/i, "drop"], [/lifeguard/i, "lifebuoy"],
  [/pavilion/i, "tent"], [/seating|patio|bench/i, "chair"], [/walking path|path|trail/i, "path"],
  [/beach access|ocean/i, "waves"], [/basketball/i, "basketball"], [/tennis|pickleball/i, "tennis-ball"],
  [/gym/i, "barbell"], [/sports field|field|soccer|baseball/i, "soccer-ball"]
];
function hdmAmenityIcon(label) {
  for (var i = 0; i < HDM_AMENITY_ICONS.length; i++) if (HDM_AMENITY_ICONS[i][0].test(label)) return HDM_AMENITY_ICONS[i][1];
  return null;
}

/* hdmIcon("clock", 16)            outline
   hdmIcon("waves", 14, "fill")    solid
   hdmIcon("waves", 14, "both")    both, for chips that switch on .active */
function hdmIcon(name, size, weight, cls) {
  var key = HDM_ICON_FOR[name] || name;
  var ic = HDM_ICONS[key];
  if (!ic) return "";
  var one = function (w, extra) {
    return '<svg class="ic' + (extra ? " " + extra : "") + (cls ? " " + cls : "") + '" viewBox="0 0 256 256" width="' + size +
      '" height="' + size + '" fill="currentColor" aria-hidden="true" focusable="false">' + (w === "fill" ? ic.f : ic.r) + "</svg>";
  };
  if (weight === "both") return one("regular", "ic-r") + one("fill", "ic-f");
  return one(weight === "fill" ? "fill" : "regular");
}
if (typeof window !== "undefined") { window.hdmIcon = hdmIcon; window.hdmAmenityIcon = hdmAmenityIcon; }
`;
writeFileSync(join(ROOT, "js/icons.js"), out, "utf8");
console.log(`js/icons.js: ${Object.keys(icons).length} icons, ${out.length} bytes`);
